#!/usr/bin/env python3
"""Normalizes Lucide icons (https://lucide.dev, ISC) for the desktop app and builds the web sprite.

    python3 scripts/build-icons.py <dir with lucide-static svgs>

Writes assets/icons/<name>.svg (used by the iced GUI) and
crates/scratchpad-web/assets/icons.svg (a <symbol> sprite used by the web UI).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "assets" / "icons"
OUT = ROOT / "assets" / "icons"
OUT.mkdir(parents=True, exist_ok=True)

symbols = []
for path in sorted(SOURCE.glob("*.svg")):
    text = path.read_text()
    body = re.search(r"<svg[^>]*>(.*)</svg>", text, re.S).group(1)
    body = re.sub(r"\s+", " ", body).strip()
    (OUT / path.name).write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
        'stroke="#000" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">' + body + "</svg>\n"
    )
    symbols.append(f'<symbol id="{path.stem}" viewBox="0 0 24 24">{body}</symbol>')

sprite = (
    "<!-- Lucide icons (https://lucide.dev), ISC license -->\n"
    '<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols) + "\n</svg>\n"
)
(ROOT / "crates" / "scratchpad-web" / "assets" / "icons.svg").write_text(sprite)

# Rust enum for the desktop app.
names = sorted(p.stem for p in OUT.glob("*.svg"))
variant = lambda n: "".join(part.capitalize() for part in n.split("-"))
rust = (
    "//! Lucide icons (<https://lucide.dev>, ISC license), tinted at render time.\n"
    "//! Generated by `scripts/build-icons.py`.\n\n"
    "use iced::widget::svg;\n\n"
    "/// The full set shared with the web UI; not every icon is used by the desktop app.\n"
    "#[allow(dead_code)]\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum Icon {\n"
    + "".join(f"    {variant(n)},\n" for n in names)
    + "}\n\nimpl Icon {\n    fn bytes(self) -> &'static [u8] {\n        match self {\n"
    + "".join(f'            Icon::{variant(n)} => include_bytes!("../../../../assets/icons/{n}.svg"),\n' for n in names)
    + "        }\n    }\n\n    pub fn handle(self) -> svg::Handle {\n        svg::Handle::from_memory(self.bytes())\n    }\n}\n\n"
    'pub const APP_LOGO: &[u8] = include_bytes!("../../../../packaging/icons/scratchpad.svg");\n'
)
(ROOT / "crates" / "scratchpad" / "src" / "gui" / "icons.rs").write_text(rust)
print(f"{len(symbols)} icons")
